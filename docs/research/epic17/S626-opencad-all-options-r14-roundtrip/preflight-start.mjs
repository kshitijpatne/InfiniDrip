import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile } from "node:fs/promises";

const dir = "docs/research/epic17/S626-opencad-all-options-r14-roundtrip";
const packet = await readFile(`${dir}/S626-start-packet.md`, "utf8");
const board = JSON.parse(await readFile("ops/control-center/data/board.json", "utf8"));
const matrixBytes = await readFile("docs/research/epic17/S330-integrated-browser/matrix.json");
const matrix = JSON.parse(matrixBytes.toString("utf8"));
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex").toUpperCase();
assert.equal(sha(matrixBytes), "69627E68F8D8E1C724C91D23FB885CBBC6B9FBCCC42512D1D4C3E19EF14D8739");
assert.equal(matrix.cases.length, 73);
assert.equal(matrix.summary.optionFieldCount, 32);
assert.deepEqual(Object.fromEntries([...new Set(matrix.cases.map((item) => item.recipeId))].map((id) => [id, matrix.cases.filter((item) => item.recipeId === id).length])), { tee: 1, fitted: 1, tank: 1, polo: 17, "woven-shirt": 28, skirt: 1, trouser: 24 });
assert([3642, 3644, 3647].includes(board.revision));
assert.equal(board.workItems.find((item) => item.id === "G04-V02")?.status, "Done");
assert.equal(board.workItems.find((item) => item.id === "G04-V03")?.status, "In Progress");
assert.equal(board.workItems.find((item) => item.id === "EPIC-17")?.status, "In Progress");
assert.equal(board.evidence.some((item) => item.id === "E-G04-S625-EXIT"), true);
assert.equal(board.evidence.some((item) => item.id === "E-G04-S626-START"), board.revision >= 3644);
assert.equal(board.evidence.some((item) => item.id === "E-G04-S626-EXIT"), board.revision === 3647);
assert.match(packet, /all 73 canonical supported-option configurations/);
assert.match(packet, /0\.001 cm/);
assert.match(packet, /no stable garment piece\/revision identifiers/);
console.log("S626 start preflight passed: clean S625 boundary, board revision 3642, canonical matrix 73/73, seven recipes, 32 option fields.");
