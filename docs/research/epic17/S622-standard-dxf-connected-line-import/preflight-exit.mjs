import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readdir, readFile } from "node:fs/promises";

const dir = "docs/research/epic17/S622-standard-dxf-connected-line-import";
const root = "C:/G04-CLO-DXF-Exchange/S622-standard-dxf-connected-line-import";
const packet = await readFile(`${dir}/S622-exit-packet.md`, "utf8");
const report = JSON.parse(await readFile(`${root}/Evidence/preexport-cut-sew-comparison.json`, "utf8"));
const board = JSON.parse(await readFile("ops/control-center/data/board.json", "utf8"));
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex");
assert.match(packet, /No DXF export was attempted/);
assert.match(packet, /4\/9/);
assert.equal(report.slice, "S622");
assert.equal(report.threshold.cm, 0.001);
assert.equal(report.summary.pieceCount, 9);
assert.equal(report.summary.canonicalCutPasses, 4);
assert.equal(report.summary.sewPasses, 4);
assert.equal(report.pieces.filter((piece) => !piece.cutPass).length, 5);
assert.equal(report.pieces.filter((piece) => !piece.sewPass).length, 5);
assert.equal(report.project.patternCount, 9);
assert.equal(report.project.getterErrors.length, 0);
assert.equal(sha(await readFile(report.input.path)), report.input.sha256);
assert.equal(sha(await readFile(report.project.path)), report.project.sha256);
assert.equal(sha(await readFile(report.renderedEvidence.pdf.path)), report.renderedEvidence.pdf.sha256);
assert.equal(sha(await readFile(report.renderedEvidence.png.path)), report.renderedEvidence.png.sha256);
assert.equal((await readdir(`${root}/Output`)).length, 0, "a DXF output exists despite the failed pre-export gate");
assert([3624, 3627].includes(board.revision));
assert.equal(board.workItems.find((item) => item.id === "G04-V03")?.status, "In Progress");
assert.equal(board.evidence.some((item) => item.id === "E-G04-S622-EXIT"), board.revision >= 3626);
assert.equal(board.evidence.some((item) => item.id === "E-G04-S622-MATRIX"), board.revision === 3627);
console.log(`S622 exit preflight passed at board revision ${board.revision}; 4/9 CUT and SEW remain intentionally failed and Output is empty.`);
