import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";

const board = JSON.parse(await readFile("ops/control-center/data/board.json", "utf8"));
assert([3564, 3566].includes(board.revision));
assert(board.evidence.some(({ id, uri, verified }) => id === "E-G04-S608-START" && uri === "docs/research/epic17/S608-clo-input-side-stage-diagnosis/S608-start-packet.md" && verified));
if (board.revision === 3564) assert(!board.evidence.some(({ id }) => id === "E-G04-S608-EXIT"));
if (board.revision === 3566) assert(board.evidence.some(({ id, uri, verified }) => id === "E-G04-S608-EXIT" && uri === "docs/research/epic17/S608-clo-input-side-stage-diagnosis/S608-exit-packet.md" && verified));
assert.equal(board.workItems.find(({ id }) => id === "EPIC-17")?.status, "In Progress");
assert.equal(board.workItems.find(({ id }) => id === "G04-V02")?.status, "Done");
assert.equal(board.workItems.find(({ id }) => id === "G04-V03")?.status, "In Progress");
const packet = await readFile("docs/research/epic17/S608-clo-input-side-stage-diagnosis/S608-exit-packet.md", "utf8");
assert(packet.includes("does **not** separate receiver import conversion"));
assert(packet.includes("None of the five S595\n  failed CUT pieces"));
assert(packet.includes("S608 clears no V03 acceptance gate"));
const report = JSON.parse(await readFile("C:/G04-CLO-DXF-Exchange/S608-clo-input-side-stage-diagnosis/Evidence/S608-stage-comparison.json", "utf8"));
assert.equal(report.getter.patternCount, 9);
assert.deepEqual(report.getter.errors, []);
assert.equal(report.cutStageComparisons.filter(({ bestGeometricCandidateToSourceCut }) => bestGeometricCandidateToSourceCut?.withinGate).length, 4);
console.log("S608 exit preflight passed; observed API limits and all V03 holds are explicit.");
