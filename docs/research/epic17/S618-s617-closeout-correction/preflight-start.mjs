import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { applyBoardCommand } from "../../../../ops/control-center/commands.mjs";
const dir="docs/research/epic17/S618-s617-closeout-correction";
const packet=await readFile(`${dir}/S618-start-packet.md`,"utf8");
assert(packet.includes("S617") && packet.toLowerCase().includes("docs-only") && packet.includes("13:01:01 UTC"));
let board=JSON.parse(await readFile("ops/control-center/data/board.json","utf8"));
assert(board.revision>=3608);
assert(board.evidence.some(x=>x.id==="E-G04-S618-START"&&x.verified));
assert.equal(board.workItems.find(x=>x.id==="EPIC-17")?.status,"In Progress");
assert.equal(board.workItems.find(x=>x.id==="G04-V02")?.status,"Done");
assert.equal(board.workItems.find(x=>x.id==="G04-V03")?.status,"In Progress");
if(board.revision===3606) for(const f of ["S618-start-add-evidence.json","S618-start-add-comment.json"]) board=applyBoardCommand(board,JSON.parse(await readFile(`${dir}/${f}`,"utf8")));
assert(board.revision>=3608); assert(board.evidence.some(x=>x.id==="E-G04-S618-START"&&x.verified));
console.log("S618 start preflight passed; validated board transition 3606→3608 keeps G04-V03 active.");
