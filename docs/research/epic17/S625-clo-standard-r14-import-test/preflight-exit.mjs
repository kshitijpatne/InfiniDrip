import assert from "node:assert/strict";
import { createHash } from "node:crypto";
import { readFile, readdir, stat } from "node:fs/promises";

const dir = "docs/research/epic17/S625-clo-standard-r14-import-test";
const root = "C:/G04-CLO-DXF-Exchange/S625-clo-standard-r14-import-test";
const packet = await readFile(`${dir}/S625-exit-packet.md`, "utf8");
const matrix = await readFile(`${dir}/V03-CURRENT-GATE-MATRIX-S625.md`, "utf8");
const infoBytes = await readFile(`${root}/Evidence/preexport-input-information.json`);
const info = JSON.parse(infoBytes.toString("utf8"));
const analysisBytes = await readFile(`${root}/Evidence/preexport-cut-sew-comparison.json`);
const analysis = JSON.parse(analysisBytes.toString("utf8"));
const sha = (bytes) => createHash("sha256").update(bytes).digest("hex").toUpperCase();
assert.equal(sha(await readFile(`${root}/Input/polo-m-r14.dxf`)), "AA6E409E84345DB89E094CC3AE8F131BEC0EC0B21373B57B3DC0DCDF7D3A7C1C");
assert.equal(sha(await readFile(`${root}/Project/polo-m-r14-standard-import.zprj`)), "AFC60121F8810D3B565415B57828973B681A699D78EBA282C188322D513FD990");
assert.equal(info.pattern_count, 9);
assert.equal(info.patterns.length, 9);
assert.equal(info.errors.length, 0);
assert.deepEqual(info.import_profile, { format: "Standard DXF", unit: "Centimeter", scale_percent: 100, rotation: "Do Not Rotate", grain: "Maintain Original", swap_cutting_and_sewing: false, include_notches: false, notch_target: null, notch_position: "Ratio", import_notch_to_enabled: true, import_notch_target: "Both", auto_distribute: false, optimize_all_curve_points: false, import_draw_curve_points: true, remove_non_grading_points: false, annotations: false, auto_trace_internal_line: false });
assert.equal(analysis.summary.cutPasses, 4);
assert.equal(analysis.summary.sewPasses, 4);
assert.equal(analysis.summary.all18Pass, false);
assert.equal(analysis.threshold.cm, 0.001);
assert.equal(analysis.infoSha256.toUpperCase(), sha(infoBytes));
assert((await readdir(`${root}/Output`)).every((name) => !name.toLowerCase().endsWith(".dxf")));
assert.equal(await stat(`${root}/Evidence/script-started.txt`).then(() => true).catch(() => false), true);
assert.match(packet, /No CLO DXF export or round trip was performed/);
assert.match(packet, /4\/9 source CUT contours and 4\/9 source SEW contours/);
assert.match(matrix, /all V03 and all-seven requirements unchanged/);
const board = JSON.parse(await readFile("ops/control-center/data/board.json", "utf8"));
assert([3639, 3642].includes(board.revision));
assert.equal(board.workItems.find((item) => item.id === "G04-V02")?.status, "Done");
assert.equal(board.workItems.find((item) => item.id === "G04-V03")?.status, "In Progress");
assert.equal(board.workItems.find((item) => item.id === "EPIC-17")?.status, "In Progress");
assert.equal(board.evidence.some((item) => item.id === "E-G04-S625-START"), true);
assert.equal(board.evidence.some((item) => item.id === "E-G04-S625-EXIT"), board.revision === 3642);
assert.equal(board.evidence.some((item) => item.id === "E-G04-S625-MATRIX"), board.revision === 3642);
console.log(`S625 exit preflight passed: 9 native patterns, zero query errors, 4/9 CUT + 4/9 SEW, no export; board revision ${board.revision}.`);
